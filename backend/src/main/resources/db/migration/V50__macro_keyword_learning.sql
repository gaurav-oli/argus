-- Self-updating macro/geopolitical keyword list for Agent 8 (MacroRelevanceTagger). A fixed keyword
-- list can never be exhaustive, so MacroKeywordLearningService keeps it growing: every time the LLM
-- classification pass (SentimentAnalyzer's "macro" field) catches a story the keyword list missed,
-- that's logged as a miss; weekly, the model proposes new keywords from real misses, and a
-- deterministic gate (corroboration + a known-ambiguous-word stoplist — NOT the model's say-so)
-- decides what actually ships. Mirrors logic_review (V35)'s "LLM proposes, evidence decides, always
-- logged" shape.

-- The live keyword list, DB-backed so a learned keyword takes effect without a redeploy.
CREATE TABLE macro_keyword (
    keyword               text         PRIMARY KEY,
    added_at              timestamptz  NOT NULL DEFAULT now(),
    source                text         NOT NULL,             -- 'seed' | 'learned'
    why                   text,                               -- model's reasoning, null for seed rows
    corroborating_misses  int                                 -- distinct misses that supported it, null for seed rows
);

