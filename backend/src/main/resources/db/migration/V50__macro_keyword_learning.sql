-- Every LLM-only catch (SentimentAnalyzer said macro=true, the keyword list hadn't already tagged it)
-- — the raw evidence the weekly review learns from.
CREATE TABLE macro_keyword_miss (
    id           bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    article_id   bigint       NOT NULL REFERENCES news_articles (id),
    headline     text         NOT NULL,
    summary      text,
    detected_at  timestamptz  NOT NULL DEFAULT now(),
    reviewed     boolean      NOT NULL DEFAULT false
);

CREATE INDEX macro_keyword_miss_unreviewed_idx ON macro_keyword_miss (reviewed) WHERE NOT reviewed;

-- Audit log of every weekly review run (adopted or not) — the "learning feedback" record.
CREATE TABLE macro_keyword_review (
    id                 bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ran_at             timestamptz  NOT NULL DEFAULT now(),
    model              text,                                 -- which model proposed (or 'n/a' when skipped)
    misses_considered  int          NOT NULL DEFAULT 0,
    proposals          jsonb        NOT NULL DEFAULT '[]'::jsonb,  -- [{keyword,why,coveredMisses}] the model suggested
    adopted            jsonb        NOT NULL DEFAULT '[]'::jsonb,  -- subset of proposals that cleared the gate
    reason             text
);

CREATE INDEX macro_keyword_review_ran_at_idx ON macro_keyword_review (ran_at DESC);
