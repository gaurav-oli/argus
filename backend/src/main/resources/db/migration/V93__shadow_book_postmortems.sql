-- Strategy rebuild, Phase 2 (docs/strategy-rebuild-plan.md): shadow trades, numeric post-mortems, rule probation.

-- Every call over the pre-registered bar gets a pretend trade with the same stop/target/trailing rules and realistic
-- fills, simulated bar by bar on daily candles. It ignores cash and position limits by design (tracked as the gap).
create table shadow_trades (
    id                bigint generated by default as identity primary key,
    recommendation_id bigint,
    ticker            text             not null,
    direction         text             not null,
    sector            text,
    entry_at          timestamptz      not null,
    entry_date        date             not null,
    entry_price       double precision not null,
    spy_entry         double precision,
    stop_price        double precision,
    initial_stop      double precision,
    target_price      double precision,
    high_water        double precision,
    stop_trailed      boolean          not null default false,
    atr_pct           double precision,
    cost_pct          double precision not null default 0,
    hold_days         integer          not null,
    status            text             not null default 'OPEN',
    scaled_out        boolean          not null default false,
    half_exit_price   double precision,
    last_eval_date    date,
    exit_date         date,
    exit_price        double precision,
    spy_exit          double precision,
    exit_reason       text,
    return_pct        double precision,
    excess_return_pct double precision,
    created_at        timestamptz      not null default now()
);
create index shadow_trades_status_idx on shadow_trades (status);
create index shadow_trades_ticker_idx on shadow_trades (ticker, direction, status);

-- One post-mortem per real or shadow trade, decided by numbers only, always measured against SPY.
create table trade_postmortem (
    id              bigint generated by default as identity primary key,
    book            text             not null,   -- REAL | SHADOW
    trade_id        bigint           not null,
    recommendation_id bigint,
    ticker          text             not null,
    direction       text             not null,
    sector          text,
    entry_date      date             not null,
    closed_date     date,
    exit_reason     text,
    excess_pct      double precision,
    hold_excess_pct double precision,
    bucket          text             not null,
    relied_on       text,
    relied_right    boolean,
    shock           boolean          not null default false,
    shock_reason    text,
    agent_checks    jsonb            not null default '{}'::jsonb,
    final           boolean          not null default false,
    updated_at      timestamptz      not null default now(),
    unique (book, trade_id)
);
create index trade_postmortem_bucket_idx on trade_postmortem (book, bucket);

-- Agent 13: a rule that passes the hold-out test runs on probation against fresh trades before it goes ACTIVE.
alter table learned_rule add column probation_started_at timestamptz;
