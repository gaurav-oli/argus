-- Every Claude Code CLI (subscription) call, so the Cost Governor panel can show how many Claude calls went through
-- the CLI versus the API key (cost_events). outcome: 'ok', or 'failed' when the call errored and the caller fell back.
create table claude_cli_calls (
    id            bigint generated by default as identity primary key,
    occurred_at   timestamptz not null default now(),
    model         text not null,
    source        text not null,
    input_tokens  bigint not null default 0,
    output_tokens bigint not null default 0,
    outcome       text not null
);
create index idx_claude_cli_calls_occurred on claude_cli_calls (occurred_at);
