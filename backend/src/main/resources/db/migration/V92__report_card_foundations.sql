-- Strategy rebuild, Phases 0–1 (docs/strategy-rebuild-plan.md).

-- One graded prediction per agent per stock per day: the agent's last word that day, scored later against SPY.
create table signal_grade (
    id                bigint generated by default as identity primary key,
    agent             text             not null,
    ticker            text             not null,
    call_date         date             not null,
    recommendation_id bigint,
    direction         text             not null,
    strength          double precision not null,
    sector            text,
    regime            text,
    earnings_week     boolean          not null default false,
    entry_date        date,
    entry_close       double precision,
    spy_entry         double precision,
    excess_5          double precision,
    excess_10         double precision,
    excess_20         double precision,
    excess_60         double precision,
    created_at        timestamptz      not null default now(),
    unique (agent, ticker, call_date)
);
create index signal_grade_date_idx on signal_grade (call_date);

-- One graded Agent 5 call per stock per day, with what the report-card weights would have said (the shadow).
create table rec_grade (
    id                bigint generated by default as identity primary key,
    ticker            text             not null,
    call_date         date             not null,
    recommendation_id bigint,
    action            text             not null,
    conviction        integer,
    actionable_bar    boolean          not null default false,
    shadow_action     text,
    shadow_conviction integer,
    sector            text,
    regime            text,
    entry_date        date,
    entry_close       double precision,
    spy_entry         double precision,
    excess_5          double precision,
    excess_10         double precision,
    excess_20         double precision,
    excess_60         double precision,
    created_at        timestamptz      not null default now(),
    unique (ticker, call_date)
);
create index rec_grade_date_idx on rec_grade (call_date);

-- Stamped when the call is made, never afterwards: the pre-registered "worth acting on" bar, and the shadow verdict.
alter table recommendations
    add column actionable_bar    boolean,
    add column bar_version       text,
    add column shadow_action     text,
    add column shadow_conviction integer;

-- Each agent's report card and the weight it earns.
create table agent_report_card (
    agent             text primary key,
    horizon_days      integer          not null,
    calls             integer          not null default 0,
    clusters          integer          not null default 0,
    edge_pct          double precision,
    hit_rate          double precision,
    strong_edge       double precision,
    weak_edge         double precision,
    strength_useful   boolean,
    mean_strength     double precision,
    situational       jsonb            not null default '{}'::jsonb,
    state             text             not null default 'UNGRADED',
    target_multiplier double precision not null default 1,
    multiplier        double precision not null default 1,
    pinned_multiplier double precision,
    updated_at        timestamptz      not null default now()
);

-- Pre-registered pass tests and live/shadow switches, one row per gated phase.
create table strategy_gate (
    name         text primary key,
    status       text        not null,
    details      jsonb       not null default '{}'::jsonb,
    evaluated_at timestamptz,
    switched_at  timestamptz,
    note         text
);

-- Realistic fills: round-trip spread + slippage + commission, in percent, subtracted from the trade's return.
alter table simulated_trades add column cost_pct numeric(8, 4) not null default 0;
