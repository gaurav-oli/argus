-- Strategy rebuild, Phase 1 model experiment: a small daily sample of headlines re-scored by a stronger Claude model,
-- next to the local model's score for the same article. The grader turns each side into a virtual agent
-- (exp-news-claude / exp-news-gemma) so the report card compares them on the same sample. Virtual agents never vote.
create table model_experiment (
    id           bigint generated by default as identity primary key,
    article_id   bigint           not null,
    ticker       text             not null,
    call_date    date             not null,
    model        text             not null,
    local_score  double precision not null,
    claude_score double precision,
    note         text,
    created_at   timestamptz      not null default now(),
    unique (article_id, ticker)
);
create index model_experiment_date_idx on model_experiment (call_date);
